import json
from pathlib import Path

import requests


OLLAMA_URL = "http://localhost:11434/api/chat"
MODEL = "gemma4:latest"

SYSTEM_PROMPT = """
Ты классификатор поведения участников Twitch-чата.

Твоя задача — анализировать последовательность сообщений и определять наблюдаемые поведенческие паттерны авторов.

Доступны только эти паттерны:

GREETING
Автор приветствует стримера или другого участника чата.
Не считать приветствием обычное упоминание пользователя, ответ на сообщение или прощание.

STREAMER_SUPPORT
Автор выражает поддержку, симпатию, похвалу, одобрение или позитивное внимание к стримеру.
Поддержка может относиться к стримеру, его игре, действиям или стриму в целом.

GAME_ADVICE
Автор рекомендует стримеру игру, которую стоит попробовать, пройти или рассмотреть.
Простое упоминание игры, рассказ о собственном опыте или обсуждение уже играемой игры не являются советом.

JOKE
Автор намеренно шутит, иронизирует или делает юмористическое замечание.
Учитывай контекст. Само по себе сообщение «лол», «ахах», «xdd», «KEKW» не является шуткой без достаточного контекста.

ARGUMENT
Автор активно участвует в споре, конфликте или перепалке с другим участником.
Обычное несогласие, критика или противоположное мнение сами по себе не являются ARGUMENT.

COPYPASTA:
Автор намеренно копирует и публикует готовый повторяющийся текстовый шаблон или намеренно повторяет одно и то же сообщение/фразу несколько раз.

COPYPASTA определяется только по факту повторения или явного использования шаблонного текста в контексте чата.

Само содержание одного сообщения НИКОГДА не является достаточным основанием для COPYPASTA.

COPYPASTA:
Автор намеренно копирует готовый текстовый шаблон, мемную фразу или содержательное сообщение, либо намеренно повторяет одну и ту же содержательную фразу несколько раз.

Само содержание одного сообщения НИКОГДА не является достаточным основанием для COPYPASTA.

Не считать COPYPASTA:
- большое количество эмодзи или Twitch-эмоутов;
- @упоминания пользователей;
- капслок;
- одну мемную или шаблонную фразу, написанную один раз;
- обычные короткие эмоциональные реакции;
- повторение «ахах», «лол», «ого», «да», «нет», «жесть» и подобных коротких реакций;
- случайные повторения;
- сообщения, которые просто похожи друг на друга.

Для COPYPASTA должен присутствовать явный признак намеренного копирования или повторения содержательной фразы.

Используй контекст соседних сообщений.
Если невозможно уверенно определить намеренное копирование, не назначай COPYPASTA.

ПРАВИЛА:

1. Используй только перечисленные паттерны.
2. Одно сообщение может иметь несколько паттернов.
3. Анализируй поведение автора сообщения, а не людей, которых автор упоминает.
4. Используй соседние сообщения как контекст, когда без них невозможно определить смысл.
5. Если паттерн не очевиден, не назначай его.
6. Лучше пропустить сомнительный паттерн, чем дать ложное срабатывание.
7. Не пытайся найти паттерн в каждом сообщении.
8. Сообщения без подходящего паттерна не включай в результат.
9. Не учитывай сообщения ботов и системные сообщения.
10. Не придумывай новые категории.
11. Не объясняй свои решения.
12. Не пиши рассуждения.
13. Верни только JSON.
14. Номера сообщений должны точно соответствовать номерам во входных данных.
15. Не изменяй и не придумывай номера сообщений.

Формат ответа:

{
"events": [
{"id": 123, "patterns": ["GREETING"]},
{"id": 124, "patterns": ["JOKE", "STREAMER_SUPPORT"]}
]
}

Если подходящих сообщений нет:

{
"events": []
}

"""


def main():
    txt_files = list(Path(".").glob("2026-09-02-test.txt"))

    if not txt_files:
        print("TXT-файл не найден.")
        return

    if len(txt_files) > 1:
        print("Найдено несколько TXT-файлов:")
        for i, file in enumerate(txt_files, 1):
            print(f"{i}. {file.name}")

        choice = int(input("Выбери файл: ")) - 1
        input_file = txt_files[choice]
    else:
        input_file = txt_files[0]

    chat_text = input_file.read_text(encoding="utf-8")

    print(f"Файл: {input_file.name}")
    print(f"Размер: {len(chat_text):,} символов")
    print("Отправляю запрос в Ollama...")

    response = requests.post(
        OLLAMA_URL,
        json={
            "model": MODEL,
            "messages": [
                {
                    "role": "system",
                    "content": SYSTEM_PROMPT,
                },
                {
                    "role": "user",
                    "content": chat_text,
                },
            ],
            "think": False,
            "stream": False,
            "options": {
                "temperature": 0.1,
                "num_ctx": 16384,
            },
        },
        timeout=600,
    )

    response.raise_for_status()

    data = response.json()
    result = data["message"]["content"]

    print("\n--- ОТВЕТ OLLAMA ---")
    print(result)

    output_file = input_file.with_name(
        input_file.stem + "_result.json"
    )

    try:
        parsed = json.loads(result)

        output_file.write_text(
            json.dumps(parsed, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )

        print(f"\nJSON сохранён: {output_file.name}")

    except json.JSONDecodeError:
        raw_file = input_file.with_name(
            input_file.stem + "_result_raw.txt"
        )

        raw_file.write_text(result, encoding="utf-8")

        print("\nОтвет не является валидным JSON.")
        print(f"Сырой ответ сохранён: {raw_file.name}")


if __name__ == "__main__":
    main()
